def _tutorial(kind=None, left=None, right=None, polyline=None, n=_N):
    """The model of Tutorial 02, with the Block Search of Tutorial 03.

    Every number is the tutorial's: the External boundary, the two material
    boundaries that bound the weak layer, the water table (assigned to both
    materials, Hu = 1, hydrostatic), the 50 kN/m2 load on the crest, the two
    materials, and the polyline. ``kind`` None leaves the object without a
    stored kind, the way a file saved before v0.1.232 reads — and imports
    nothing this version added, so the tests that use it discriminate the
    old tree by behaviour and not by a missing name.
    """
    from ogr_core.geometry import Boundary, BoundaryType, Polyline, Vertex
    from ogr_core.loads import DistributedLoad, LoadDistribution
    from ogr_core.materials import Material, PorePressureType
    from ogr_core.materials.builtin_models import MohrCoulomb
    from ogr_core.project import Project

    p = Project("Tutorial 02/03")
    ext = Polyline(vertices=[Vertex(*v) for v in (
        (5, 0), (100, 0), (100, 34), (100, 36), (100, 40), (67, 40),
        (43, 28), (5, 28), (5, 18), (5, 16))], closed=True)
    ext.ensure_ccw()
    p.add_boundary(Boundary(polyline=ext, btype=BoundaryType.EXTERNAL))
    for a, b in (((5, 18), (100, 36)), ((5, 16), (100, 34))):
        p.add_boundary(Boundary(polyline=Polyline(
            vertices=[Vertex(*a), Vertex(*b)], closed=False),
            btype=BoundaryType.MATERIAL))
    wt = Boundary(polyline=Polyline(vertices=[Vertex(*v) for v in (
        (5, 28), (43, 28), (49, 30), (60, 34), (66, 36), (74, 38),
        (80, 38.5), (100, 38.5))], closed=False),
        btype=BoundaryType.WATER_TABLE)
    p.add_boundary(wt)
    soil = Material(name="soil 1", unit_weight=19.0,
                    strength=MohrCoulomb(cohesion=28.5, friction_angle=20.0),
                    pore_pressure=PorePressureType.WATER_TABLE,
                    water_surface_id=wt.id)
    weak = Material(name="weak layer", unit_weight=18.5,
                    strength=MohrCoulomb(cohesion=0.0, friction_angle=10.0),
                    pore_pressure=PorePressureType.WATER_TABLE,
                    water_surface_id=wt.id)
    p.materials = [soil, weak]
    p.resolve_regions()
    p.assign_material_at(50.0, 10.0, soil.id)
    p.assign_material_at(50.0, _layer_mid(50.0), weak.id)
    p.assign_material_at(50.0, 29.0, soil.id)
    p.add_distributed_load(DistributedLoad(
        start=Vertex(70.0, 40.0), end=Vertex(80.0, 40.0), magnitude_1=50.0,
        distribution=LoadDistribution.CONSTANT))
    pts = polyline or ((39.0, 23.0), (81.0, 31.0))
    obj = Boundary(polyline=Polyline(vertices=[Vertex(*v) for v in pts],
                                     closed=False),
                   btype=BoundaryType.BLOCK_SEARCH_OBJECT)
    if kind is not None:
        from ogr_core.geometry import BlockObjectSpec
        spec = BlockObjectSpec(kind=kind)
        if left is not None:
            spec.left_point = left
        if right is not None:
            spec.right_point = right
        obj.block_object = spec
    p.add_boundary(obj)
    s = p.settings.search
    s.surface_type = "non_circular"
    s.search_method = "block"
    s.block_num_surfaces = n
    s.block_left_start_angle_deg = s.block_left_end_angle_deg = 135.0
    s.block_right_start_angle_deg = s.block_right_end_angle_deg = 45.0
    return p


def _layer_mid(x: float) -> float:
    """The middle of the weak layer at ``x`` (between (5,16)-(100,34) and
    (5,18)-(100,36))."""
    return 17.0 + (x - 5.0) * 18.0 / 95.0


def _run(key, **kw):
    """A Bishop Block Search on the tutorial model, cached by ``key``."""
    if key not in _CACHE:
        from ogr_slip2d.analysis_runner import build_search
        p = _tutorial(**kw)
        _CACHE[key] = (p, build_search(p, "bishop_simplified").run(p))
    return _CACHE[key]


def _polyline_run():
    from ogr_core.geometry import BlockObjectKind
    return _run("polyline", kind=BlockObjectKind.POLYLINE)


def _dist_to_polyline(x, y, pts) -> float:
    best = float("inf")
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        dx, dy = bx - ax, by - ay
        t = max(0.0, min(1.0, ((x - ax) * dx + (y - ay) * dy)
                         / (dx * dx + dy * dy)))
        best = min(best, math.hypot(x - ax - t * dx, y - ay - t * dy))
    return best


