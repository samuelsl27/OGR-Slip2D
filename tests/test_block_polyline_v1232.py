"""
Tests for v0.1.232 — the Block Search Polyline exists, and every Block
Search object says which of the four it is. Defect D109.

**The invariant**: a Block Search object gives each trial surface exactly
what the reference says its kind gives. A Window, a Line and a Point give
ONE vertex (at random inside, at random along, and the point itself); a
Polyline gives TWO points along it AND the stretch of polyline between
them — «The slip surface will then be constrained to follow the polyline,
BETWEEN the two points». How each of its two points is generated is chosen
per side: anywhere along the polyline, anywhere on its end segment, or at
its end vertex.

**What was wrong.** OGR inferred the kind from the vertex count on every
trial surface and took ONE point from every object, so the Polyline did
not exist: a surface could touch a weak layer at one point and never run
along it. Verification problem 75 publishes a flat of 80.4 m on the top of
its till, and the Block Search could not reach it by construction (its
archived critical surfaces have three vertices). The kind is now stored
on the object (``Boundary.block_object``), because a two-vertex Line and a
two-vertex Polyline cannot be told apart by their vertices.

**External anchor (rule 1): Tutorial 03 of the reference's own manual**
(Non-Circular Surfaces). It runs on the model of Tutorial 02 (Materials &
Loading), whose text gives every coordinate, material and load; the
tutorial adds a one-segment polyline (39, 23)-(81, 31) inside the weak
layer, both points «Any Line Segment», projection angles fixed at 135° and
45°, 5000 surfaces. Two published statements are checked:

* «all slip surfaces generated by the search, will consist of three line
  segments - a line segment along the Block Search Polyline, and the left
  and right projected segments» — an identity, on every generated surface;
* «The Global Minimum safety factor for a Bishop analysis is 0.762» —
  within 3 %, with 300 surfaces. OGR finds 0.755177 with 300 and 0.747654
  with 5000 (measured in v0.1.232 with the project's seed): BELOW the
  published minimum, as a search that happened to sample the family more
  finely would. With the angles fixed the family has two dimensions, the
  two points along the segment, so both searches sample the same set of
  surfaces with different random numbers; the 3 % is the room that needs.
  Nothing was tuned towards 0.762. The slice count is OGR's default (25);
  the tutorial does not state the reference's.

**Identities**:

* Polyline population: the vertices between the two projected ends lie on
  the polyline, and every vertex of the polyline strictly between the
  first and the last of them is present.
* End Point puts that side's point ON the end vertex for every surface;
  Line Segment keeps it on the end segment.
* An object saved before v0.1.232 stores no kind. Two open vertices without
  a kind are a LINE and give exactly the trial surfaces of an object
  declared a Line, bit for bit — which is what keeps every model of the
  verification bank on its digits.

**Rule 7**: the same two vertices declared Line and Polyline give 1.997758
and 0.755177 (measured); each point option moves the minimum too.

COST. The anchor model is small; seven Block Searches of 300 surfaces and a
handful of rule checks, about 25 s. One MainWindow for the interface
checks.
"""
