def _menu_texts(w, title):
    from ogr_gui.i18n import tr
    for a in w.menuBar().actions():
        if a.text().replace("&", "") == tr(title):
            return [x.text() for x in a.menu().actions()]
    return []


@_requires_qt
class TestTheInterfaceDrawsAllFour:

    def test_the_four_actions_are_in_the_surfaces_menu(self):
        """Rule 3: reachable from the menu bar, under the reference's names."""
        w = _window()
        texts = _menu_texts(w, "Surfaces")
        for key in ("block_object", "block_line", "block_point",
                    "block_polyline"):
            assert w._actions[key].text() in texts, key
        assert w._actions["block_object"].text() == "Add Block Search Window"

    def test_each_mode_stores_its_kind(self):
        from ogr_core.geometry import BlockObjectKind, BoundaryType
        from ogr_gui.canvas.tool_mode import ToolMode
        w = _window()
        before = len(w.project.boundaries)
        previous = w.project.settings.search.search_method
        try:
            w.project.settings.search.search_method = "block"
            w.canvas.set_tool_mode(ToolMode.DRAW_BLOCK_POINT)
            w.canvas.add_manual_point(10.0, 5.0)        # one click finishes
            w.canvas.set_tool_mode(ToolMode.DRAW_BLOCK_LINE)
            w.canvas.add_manual_point(10.0, 5.0)
            w.canvas.add_manual_point(20.0, 6.0)        # two clicks finish
            w.canvas.set_tool_mode(ToolMode.DRAW_BLOCK_POLYLINE)
            for x, y in ((10.0, 5.0), (20.0, 6.0), (30.0, 6.5)):
                w.canvas.add_manual_point(x, y)
            w.canvas._finish_drawing()
            added = w.project.boundaries[before:]
            assert [b.btype for b in added] == \
                [BoundaryType.BLOCK_SEARCH_OBJECT] * 3
            assert [b.block_object.kind for b in added] == [
                BlockObjectKind.POINT, BlockObjectKind.LINE,
                BlockObjectKind.POLYLINE]
            assert [len(b.polyline.vertices) for b in added] == [1, 2, 3]
            # The Polyline opened its options, not modal.
            dlg = w._block_object_dialog
            assert dlg is not None and not dlg.isModal()
        finally:
            dlg = getattr(w, "_block_object_dialog", None)
            if dlg is not None:
                dlg.close()
            while len(w.project.boundaries) > before:
                w.project.boundaries.pop()
            w.project.settings.search.search_method = previous
            w.canvas.set_tool_mode(ToolMode.SELECT)

    def test_the_dialog_sets_the_point_options_undoably(self):
        from ogr_core.geometry import (BlockObjectKind, BlockObjectSpec,
                                       Boundary, BoundaryType,
                                       PolylinePointMode, Polyline, Vertex)
        from ogr_gui.dialogs import BlockObjectDialog
        w = _window()
        obj = Boundary(polyline=Polyline(vertices=[
            Vertex(10, 5), Vertex(20, 6), Vertex(30, 6.5)]),
            btype=BoundaryType.BLOCK_SEARCH_OBJECT,
            block_object=BlockObjectSpec(BlockObjectKind.POLYLINE))
        w.project.boundaries.append(obj)
        try:
            dlg = BlockObjectDialog(obj, w)
            dlg.cbo_left.setCurrentIndex(
                dlg.cbo_left.findData(PolylinePointMode.SEGMENT))
            dlg.cbo_right.setCurrentIndex(
                dlg.cbo_right.findData(PolylinePointMode.END_POINT))
            assert w.apply_block_object_spec(obj.id, dlg.spec())
            now = next(b for b in w.project.boundaries if b.id == obj.id)
            assert now.block_object.left_point is PolylinePointMode.SEGMENT
            assert now.block_object.right_point is \
                PolylinePointMode.END_POINT
            w.command_stack.undo(w.project)
            now = next(b for b in w.project.boundaries if b.id == obj.id)
            assert now.block_object.left_point is PolylinePointMode.ANY
            dlg.close()
        finally:
            w.project.boundaries[:] = [b for b in w.project.boundaries
                                       if b.id != obj.id]

    def test_a_point_can_be_picked_and_is_drawn(self):
        from ogr_core.geometry import (Boundary, BoundaryType, Polyline,
                                       Vertex)
        from ogr_gui.canvas.graphics_items import BoundaryItem
        from PySide6.QtWidgets import QGraphicsItem
        w = _window()
        obj = Boundary(polyline=Polyline(vertices=[Vertex(12.0, 7.0)]),
                       btype=BoundaryType.BLOCK_SEARCH_OBJECT)
        w.project.boundaries.append(obj)
        try:
            idx = w.canvas._pick_boundary(12.0, 7.0)
            assert w.project.boundaries[idx] is obj
            item = BoundaryItem(obj)
            assert not item.path().isEmpty()
            assert item.flags() & \
                QGraphicsItem.GraphicsItemFlag.ItemIgnoresTransformations
        finally:
            w.project.boundaries.remove(obj)
